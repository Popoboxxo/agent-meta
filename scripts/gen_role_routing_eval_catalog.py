#!/usr/bin/env python3
"""Generate the role-routing eval corpus (IC-13, AC-03, AC-62 corpus part).

Reads ``config/role-defaults.yaml`` (keywords + examples per role) and emits:

* ``tests/routing-llm-eval/roles/catalog.generated.yaml`` -- literal positive
  cases for every keyword/example, one EN case per pattern role, collision
  cases for every cross-role keyword (IC-29 overlap tokens) and direct
  addressing cases for ``name_only`` roles.
* ``tests/routing-llm-eval/roles/promptfooconfig.generated.yaml`` -- promptfoo
  config merging the generated catalog and the hand-written
  ``catalog.manual.yaml`` (which is never rewritten by this script).

Case schema: ``expected: {target, tier_escalation}`` where ``target`` is a role
name, ``pipeline:<name>`` or ``ASK``; ``tier_escalation`` is true iff the target
role is ``routing.orchestrator_only``.

The output is deterministic (role-defaults order, no timestamps). No LLM call
and no network access happens here; running the eval itself is gated by IC-36.

Usage:
    python3 scripts/gen_role_routing_eval_catalog.py             # write files
    python3 scripts/gen_role_routing_eval_catalog.py --check     # exit 1 if stale
    python3 scripts/gen_role_routing_eval_catalog.py --print-hash  # corpus sha256
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from collections import defaultdict
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

try:
    import yaml  # type: ignore[import]
except ImportError:
    print("PyYAML is required (pip install pyyaml).", file=sys.stderr)
    sys.exit(1)

from scripts.lib.roles import load_roles_config

DEFAULT_OUT_DIR = _REPO_ROOT / "tests" / "routing-llm-eval" / "roles"
GENERATED_NAME = "catalog.generated.yaml"
MANUAL_NAME = "catalog.manual.yaml"
PROMPTFOO_NAME = "promptfooconfig.generated.yaml"

CATALOG_HEADER = (
    "# GENERATED by scripts/gen_role_routing_eval_catalog.py -- DO NOT EDIT.\n"
    "# Source: config/role-defaults.yaml (routing_patterns, routing). Hand-written\n"
    "# additions belong in catalog.manual.yaml. Regenerate:\n"
    "#   python3 scripts/gen_role_routing_eval_catalog.py\n"
)
PROMPTFOO_HEADER = (
    "# GENERATED by scripts/gen_role_routing_eval_catalog.py -- DO NOT EDIT.\n"
    "# Source of truth: catalog.generated.yaml + catalog.manual.yaml next to this file.\n"
)

PROVIDERS = [
    {"id": "exec", "label": "claude-orchestrator", "command": ["../provider-claude.sh"]},
    {"id": "exec", "label": "opencode-orchestrator", "command": ["../provider-opencode.sh"]},
]


def _norm(token: object) -> str:
    return str(token).strip().casefold()


def _expected(roles: dict, target: str) -> dict:
    info = roles.get(target) or {}
    escalate = bool((info.get("routing") or {}).get("orchestrator_only"))
    return {"target": target, "tier_escalation": escalate}


def _patterns(info: dict) -> tuple:
    patterns = info.get("routing_patterns") or {}
    return list(patterns.get("keywords") or []), list(patterns.get("examples") or [])


def _overlap_index(roles: dict) -> dict:
    """normalized keyword -> sorted owner roles, only for tokens owned by >1 role."""
    owners: dict = defaultdict(set)
    for name, info in roles.items():
        for kw in _patterns(info)[0]:
            owners[_norm(kw)].add(name)
    return {t: sorted(r) for t, r in sorted(owners.items()) if len(r) > 1}


def generate_catalog(agent_meta_root: Path) -> dict:
    """Build the generated corpus as ``{"cases": [...]}`` (deterministic)."""
    roles = load_roles_config(Path(agent_meta_root))["roles"]
    overlaps = _overlap_index(roles)
    cases: list = []

    def add(case_id, role, category, lang, task, target, **extra):
        case = {"id": case_id, "role": role, "category": category, "lang": lang, "task": task}
        case.update(extra)
        case["expected"] = _expected(roles, target)
        cases.append(case)

    for name, info in roles.items():
        addressability = (info.get("routing") or {}).get("addressability")
        if addressability == "excluded":
            continue
        keywords, examples = _patterns(info)

        n_kw = 0
        first_plain = None
        for kw in keywords:
            if _norm(kw) in overlaps:
                continue  # covered by collision cases below
            n_kw += 1
            first_plain = first_plain or kw
            add(f"rk-{name}-{n_kw:02d}", name, "keyword", "de",
                f"Bitte übernimm: {kw}.", name, source_keyword=kw)
        if first_plain is not None:
            add(f"rk-{name}-en", name, "keyword", "en",
                f"Please handle this: {first_plain}.", name, source_keyword=first_plain)
        for n_ex, example in enumerate(examples, start=1):
            add(f"rx-{name}-{n_ex:02d}", name, "example", "de", example, name,
                source_example=example)

        if addressability == "name_only":
            add(f"rn-{name}-de", name, "name_only", "de",
                f"Rufe den Agenten {name} auf und starte direkt.", name)
            add(f"rn-{name}-en", name, "name_only", "en",
                f"Run the {name} agent directly.", name)

    # Collision cases: one DE + one EN case per owner role of every overlap token,
    # disambiguated by the owner's own example, plus a bare-token ASK case.
    for token, owners in overlaps.items():
        slug = token.replace(" ", "-")
        for owner in owners:
            keywords, examples = _patterns(roles[owner])
            kw = next(k for k in keywords if _norm(k) == token)
            base = examples[0] if examples else (roles[owner].get("description") or owner)
            add(f"rc-{slug}-{owner}-de", owner, "collision", "de",
                f"{base} Stichwort: {kw}.", owner,
                source_keyword=kw, overlap_token=token)
            add(f"rc-{slug}-{owner}-en", owner, "collision", "en",
                f"Request: {base} Keyword: {kw}.", owner,
                source_keyword=kw, overlap_token=token)
        add(f"rc-{slug}-ask", "orchestrator", "ambiguous", "de",
            f"Kümmere dich um: {token}.", "ASK", overlap_token=token)

    return {"cases": cases}


def render_catalog(catalog: dict) -> str:
    body = yaml.safe_dump(catalog, allow_unicode=True, sort_keys=False,
                          default_flow_style=False, width=100)
    return CATALOG_HEADER + body


def catalog_hash(path: Path) -> str:
    """sha256 over the bytes of the (generated) catalog file."""
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _assertion(expected: dict) -> list:
    schema = {
        "type": "object",
        "required": ["target"],
        "properties": {"target": {"const": expected["target"]}},
    }
    if expected["tier_escalation"]:
        schema["required"].append("tier_escalation")
        schema["properties"]["tier_escalation"] = {"const": True}
    return [{"type": "contains-json", "value": schema}]


def build_promptfoo_config(generated: list, manual: list) -> dict:
    tests = []
    for case in list(generated) + list(manual):
        tests.append({
            "description": f"{case['id']} [{case['role']}]",
            "vars": {"role": "orchestrator", "prompt": case["task"]},
            "assert": _assertion(case["expected"]),
        })
    return {
        "# note": (
            "Expected output per case: JSON {target, tier_escalation?}. Providers carry\n"
            "no {{prompt}} placeholder (promptfoo appends it as last argv element).\n"
            "Running this eval is cost-gated (IC-36): never automatic."
        ),
        "defaultTest": {"options": {"provider": {"wrapping": False}}},
        "providers": PROVIDERS,
        "tests": tests,
    }


def render_outputs(agent_meta_root: Path, out_dir: Path) -> dict:
    """Return {filename: content} for the generated files (manual catalog read-only)."""
    catalog = generate_catalog(agent_meta_root)
    manual_path = out_dir / MANUAL_NAME
    manual = []
    if manual_path.exists():
        manual = (yaml.safe_load(manual_path.read_text(encoding="utf-8")) or {}).get("cases", [])
    config = build_promptfoo_config(catalog["cases"], manual)
    return {
        GENERATED_NAME: render_catalog(catalog),
        PROMPTFOO_NAME: PROMPTFOO_HEADER + yaml.safe_dump(
            config, sort_keys=False, allow_unicode=True, width=100),
    }


def main(argv: list = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR),
                        help="Directory holding the roles catalogs.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if files are stale.")
    parser.add_argument("--print-hash", action="store_true",
                        help="Print sha256 of the generated catalog and exit.")
    args = parser.parse_args(argv)
    out_dir = Path(args.out_dir)
    # The manual catalog is an input: when writing to a foreign dir, read the repo copy.
    manual_src = out_dir if (out_dir / MANUAL_NAME).exists() else DEFAULT_OUT_DIR
    outputs = render_outputs(_REPO_ROOT, manual_src)

    if args.print_hash:
        print(hashlib.sha256(outputs[GENERATED_NAME].encode("utf-8")).hexdigest())
        return 0
    if args.check:
        stale = [n for n, c in outputs.items()
                 if not (out_dir / n).exists()
                 or (out_dir / n).read_bytes() != c.encode("utf-8")]
        if stale:
            print(f"[gen-role-routing-eval] stale: {', '.join(stale)} -- regenerate.",
                  file=sys.stderr)
            return 1
        print("[gen-role-routing-eval] up to date.")
        return 0
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (out_dir / name).write_bytes(content.encode("utf-8"))
    print(f"[gen-role-routing-eval] wrote {len(outputs)} files to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
