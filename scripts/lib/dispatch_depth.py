"""Provider dispatch-depth config (IC-15 Nr. 4, SPEC-CONTEXT-PROFILES-2026-10-11).

A spawned orchestrator child keeps its multi-agent dispatch tools only when the
provider's committed TOML config declares ``[agents] max_depth`` (study §3.2:
"keine Multi-Agent-Tools bei Default-Config"). This module writes that table.

Gating is entirely capability-driven — ``agent_config_format`` (value ``toml``)
plus ``required_depth`` — never on a provider name
(``tests/test_provider_agnostic_dispatch.py``). The target file is the
provider's committed config artifact (``mcp-config.committed-file``), the same
path the ``dispatch-depth-missing`` doctor seed reads
(``config/known-issues.yaml``).
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Mapping

from .io import safe_path

_BLOCK_BEGIN = "# agent-meta:agents-begin"
_BLOCK_END = "# agent-meta:agents-end"
_BLOCK_RE = re.compile(
    rf"^{re.escape(_BLOCK_BEGIN)}.*?^{re.escape(_BLOCK_END)}",
    re.MULTILINE | re.DOTALL,
)


def _required_depth(capabilities: Mapping):
    """``required_depth`` as a positive int, else ``None`` (bool is rejected)."""
    depth = capabilities.get("required_depth")
    if isinstance(depth, int) and not isinstance(depth, bool) and depth >= 1:
        return depth
    return None


def _config_file(pc: Mapping):
    """The provider's committed config file (``mcp-config.committed-file``)."""
    mcp_config = pc.get("mcp-config") or {}
    committed = mcp_config.get("committed-file")
    if isinstance(committed, str) and committed.strip():
        return committed
    return None


def dispatch_depth_supported(pc: Mapping, capabilities: Mapping) -> bool:
    """True when the capability data requests a TOML ``[agents]`` depth write."""
    return (
        capabilities.get("agent_config_format") == "toml"
        and _required_depth(capabilities) is not None
        and _config_file(pc) is not None
    )


def _render_block(depth: int) -> str:
    return (
        f"{_BLOCK_BEGIN}\n"
        "# Generated by agent-meta — do not edit manually.\n"
        "[agents]\n"
        f"max_depth = {depth}\n"
        f"{_BLOCK_END}"
    )


def _merge(existing: str, block: str) -> str:
    """Replace the managed agents block in place, else append it at the end."""
    if _BLOCK_RE.search(existing):
        return _BLOCK_RE.sub(lambda _m: block, existing, count=1)
    return existing.rstrip("\n") + "\n\n" + block + "\n"


def write_dispatch_depth_config(
    project_root: Path,
    pc: Mapping,
    capabilities: Mapping,
    dry_run: bool = False,
) -> list[str]:
    """Write ``[agents] max_depth >= required_depth`` into the provider config.

    Returns the relative path it wrote (or ``[]`` when the provider is not
    TOML-configured, declares no ``required_depth``, or the managed block is
    already current). ``dry_run`` computes the same result without writing.
    """
    if not dispatch_depth_supported(pc, capabilities):
        return []
    rel = _config_file(pc)
    depth = _required_depth(capabilities)
    path = safe_path(project_root, rel)
    block = _render_block(depth)
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        new_content = _merge(existing, block)
        if new_content == existing:
            return []
    else:
        new_content = "# Provider config — managed by agent-meta.\n\n" + block + "\n"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new_content, encoding="utf-8")
    return [rel]
